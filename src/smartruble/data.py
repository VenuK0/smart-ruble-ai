def _noise(rng: random.Random, s: str) -> str:
    if len(s) > 4 and rng.random() < 0.15:  # опечатка: пропуск символа
        i = rng.randrange(1, len(s) - 1)
        s = s[:i] + s[i + 1:]
    if rng.random() < 0.3:
        s = s.upper()
    elif rng.random() < 0.3:
        s = s.capitalize()
    return s


def make_items(n_per_class: int = 300, seed: int = 0):
    """Возвращает список (название, категория, базовое_название)."""
    rng = random.Random(seed)
    rows = []
    for cat, bases in BASES.items():
        for _ in range(n_per_class):
            base = rng.choice(bases)
            mod = rng.choice(MODS)
            name = _noise(rng, f"{base} {mod}".strip())
            rows.append((name, cat, base))
    rng.shuffle(rows)
    return rows


def split_by_base(rows, test_share: float = 0.3, seed: int = 0):
    """Делим по базовым названиям: в тесте только позиции, которых модель не видела."""
    rng = random.Random(seed)
    test_bases = set()
    for cat, bases in BASES.items():
        k = max(1, int(len(bases) * test_share))
        test_bases.update(rng.sample(bases, k))
    train = [r for r in rows if r[2] not in test_bases]
    test = [r for r in rows if r[2] in test_bases]
    return train, test


def make_transactions(seed: int = 0, n_students: int = 60, n_good: int = 40, n_fraud: int = 4):
    """Синтетический граф «студент — мерчант». Возвращает (транзакции, множество мошеннических мерчантов)."""
    rng = random.Random(seed)
    students = [f"S{i:03d}" for i in range(n_students)]
    tx, fraud = [], set()
    for m in range(n_good):
        mid = f"M{m:03d}"
        for _ in range(rng.randint(15, 60)):
            tx.append({"merchant": mid, "student": rng.choice(students), "amount": round(rng.lognormvariate(7.0, 1.0), 2),
                       "hour": min(23, max(6, int(rng.gauss(14, 3.5))))})
    for f in range(n_fraud):
        mid = f"F{f:03d}"
        fraud.add(mid)
        ring = rng.sample(students, 3)
        for _ in range(rng.randint(12, 25)):
            tx.append({"merchant": mid, "student": rng.choice(ring), "amount": float(rng.choice([30000, 50000, 70000, 80000])),
                       "hour": rng.choice([0, 1, 2, 3, 22, 23])})
    rng.shuffle(tx)
    return tx, fraud
